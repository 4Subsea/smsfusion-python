def white_noise(
    N: float,
    fs: float,
    n: int,
    seed: int | np.random.Generator | None = None,
) -> NDArray[np.float64]:
    """
    Generates a discrete-time (bandlimited) Gaussian white noise sequence.

    Bandlimited white noise is characterized by a spectral amplitude which is
    constant over the bandwidth, and zero outside that range. I.e.,::

        S(w) = N ** 2,  for ``|w|`` <= 2*pi*W

        S(w) = 0,       for ``|w|`` > 2*pi*W

    where ``W = fs / 2`` is the bandwidth in hertz, and ``N`` is the spectral
    density coefficient.

    The returned white sequence will thus have a variance of ``N ** 2 * fs``.

    Parameters
    ----------
    N : float
        Spectral density coefficient.
    fs : float
        Sampling frequency in Hz.
    n : int
        Number of samples to generate.
    seed : int, np.random.Generator or None, optional
        A seed used to initialize a random number generator. If passed a Generator,
        it will be used unaltered.

    Returns
    -------
    numpy.ndarray, shape (n,)
        Discrete time Gaussian white noise sequence.

    See Also
    --------
    smsfusion.gauss_markov, smsfusion.random_walk
    """
    rng = np.random.default_rng(seed)
    sigma_wn = N * np.sqrt(fs)
    wn = sigma_wn * rng.standard_normal(n)  # type: ignore[no-any-return]
    return wn


def random_walk(
    K: float, fs: float, n: int, seed: int | np.random.Generator | None = None
) -> NDArray[np.float64]:
    """
    Generates a discrete-time random walk (i.e., Brownian noise) sequence.

    The random walk process is characterized by a power spectrum::

        S(w) = K ** 2 / w ** 2

    where ``K`` is the spectral density coefficient, and ``w`` is the angular
    frequency.

    A discrete-time realization of the process is generated by the recursive
    equation::

        X[k+1] = X[k] + W[k]

    with ``W[k]`` being a zero-mean Gaussian white noise sequence with standard
    deviation::

        sigma_wn = K / sqrt(fs)

    The sequence starts always at 0.

    Parameters
    ----------
    K : float
        Spectral density coefficient.
    fs : float
        Sampling frequency in Hz.
    n : int
        Number of samples to generate.
    seed: int, np.random.Generator or None, optional
        A seed used to initialize a random number generator. If passed a Generator,
        it will be used unaltered.

    Returns
    -------
    numpy.ndarray, shape (n,)
        Discrete-time random walk sequence.

    See Also
    --------
    smsfusion.gauss_markov, smsfusion.white_noise
    """
    rng = np.random.default_rng(seed)

    sigma_wn = K / np.sqrt(fs)

    x = np.zeros(n)
    epsilon = rng.standard_normal(n - 1)
    for i in range(1, n):
        x[i] = x[i - 1] + sigma_wn * epsilon[i - 1]

    return x


def gauss_markov(
    sigma: float,
    tau_c: float,
    fs: float,
    n: int,
    seed: int | np.random.Generator | None = None,
) -> NDArray[np.float64]:
    """
    Generates a discrete-time first-order Gauss-Markov sequence.

    The first-order Gauss-Markov process is characterized by a power spectrum::

        S(w) = 2 * sigma**2 * beta / (w**2 + beta**2)

    where ``sigma`` is the long-term standard deviation of the process,
    ``tau_c = 1 / beta`` is the correlation time, and ``w`` is the angular
    frequency.

    A discrete-time realization of the process is generated by the recursive
    equation (see reference [1]_)::

        X[k+1] = exp(-beta * dt) * X[k] + W[k]

    with ``W[k]`` being a zero-mean Gaussian white noise sequence with standard
    deviation::

        sigma_wn = sigma * sqrt(1 - exp(-2 * beta * dt))

    The sequence starts always at 0.

    Parameters
    ----------
    sigma : float
        Standard deviation (i.e., root-mean-square value) of the process.
    tau_c : float
        Correlation time in seconds.
    fs : float
        Sampling frequency in Hz.
    n : int
        Number of samples to generate.
    seed : int, np.random.Generator or None, optional
        A seed used to initialize a random number generator. If passed a Generator,
        it will be used unaltered.

    Returns
    -------
    numpy.ndarray, shape (n,)
        Discrete-time first-order Gauss-Markov sequence.

    References
    ----------
    .. [1] Brown R.G. & Hwang P.Y.C., "Random Signals and Applied Kalman
       Filtering", 4th ed., p. 78-79 and 100, Wiley, 2012.

    See Also
    --------
    smsfusion.random_walk, smsfusion.white_noise
    """
    rng = np.random.default_rng(seed)

    dt = 1.0 / fs
    beta = 1.0 / tau_c

    phi = np.exp(-beta * dt)
    sigma_wn = sigma * np.sqrt(1.0 - np.exp(-2 * beta * dt))

    x = np.zeros(n)
    epsilon = rng.standard_normal(n - 1)
    for i in range(1, n):
        x[i] = phi * x[i - 1] + sigma_wn * epsilon[i - 1]

    return x


class NoiseModel:
    """
    Provides an interface for generating random sensor noise with the following
    contributions:

    - **N**: White noise
    - **B**: Flicker noise (sometimes referred to as 'pink noise' or 'bias instability')
    - **K**: Drift / Brownian noise (optional)
    - **bc**: Constant bias (optional)

    A white sequence, ``WN[k]``, with spectral density ``N**2`` is generated by drawing samples
    from a Normal distribution with standard deviation ``N * sqrt(fs)``.

    A flicker noise (or pink noise) sequence, ``PN[k]``, is simulated using a first-order
    Gauss-Markov (GM) process with long-term standard deviation ``B`` and correlation
    time ``tau_cb``.

    A Brownian noise (or drift) sequence, ``BN[k]``, is simulated using one of the
    following processes, depending on whether the correlation time, ``tau_ck``,
    is provided or not:

    - Random walk (RW) process (if no correlation time ``tau_ck`` is provided).
    - First-order Gauss-Markov (GM) process, with a long-term  standard deviation
      ``K * sqrt(tau_ck / 2)`` and correlation time ``tau_ck``.

    The total noise is computed as::

        err[k] = bc + WN[k] + PN[k] + BN[k]

    where ``WN[k]``, ``PN[k]``, and ``BN[k]`` represent the white, flicker, and Brownian
    noise contributions, respectively.

    Parameters
    ----------
    N : float
        White noise spectral density coefficient given in units ``V/sqrt(Hz)``,
        where ``V`` represents the unit of the desired output noise.
    B : float
        Bias stability given in the same units as the desired output noise; represents
        the power spectral density coefficient for the flicker noise (or pink noise).
    tau_cb : float
        Correlation time in seconds for the flicker noise (i.e., pink noise).
    K : float, optional
        Drift rate given in units ``V*sqrt(Hz)``, where ``V`` represents the unit
        of the desired output noise; represents the power spectral density coefficient
        of the Brownian noise component. If ``None``, the Brownian noise contribution
        is excluded.
    tau_ck : float, optional
        Correlation time in seconds for the Brownian noise (drift). If ``None``, the
        Brownian noise is modeled as a random walk (RW) process. Otherwise, it
        is modeled as a first-order Gauss-Markov (GM) process.
    bc : float, optional
        Constant bias given in the same units as the output noise.
    seed : int, optional
        A seed used to initialize the random number generator.

    See Also
    --------
    smsfusion.gauss_markov
    smsfusion.random_walk
    smsfusion.white_noise
    """

    def __init__(
        self,
        N: float,
        B: float,
        tau_cb: float,
        K: float | None = None,
        tau_ck: float | None = None,
        bc: float | None = None,
        seed: int | None = None,
    ) -> None:
        self._N = N
        self._B = B
        self._tau_cb = tau_cb
        self._K = K
        self._tau_ck = tau_ck
        self._bc = bc or 0.0
        self._rng = np.random.default_rng(seed)

    def __call__(self, fs: float, n: int) -> NDArray[np.float64]:
        """
        Generates a discrete-time random noise sequence.

        Parameters
        ----------
        fs : float
            Sampling frequency in Hz.
        n : int
            Number of samples to generate.

        Returns
        -------
        numpy.ndarray, shape (n,)
            Noise sequence.

        Notes
        -----
        The generated noise will have units corresponding to the noise
        parameters given during initialization.
        """
        # Constant bias
        bc = self._bc

        # White noise
        wn = white_noise(self._N, fs, n, seed=self._rng)

        # Flicker noise / pink noise
        pn = gauss_markov(self._B, self._tau_cb, fs, n, seed=self._rng)

        # Drift / Brownian noise
        if self._K and self._tau_ck:
            sigma = self._K * np.sqrt(self._tau_ck / 2.0)
            bn = gauss_markov(sigma, self._tau_ck, fs, n, seed=self._rng)
        elif self._K:
            bn = random_walk(self._K, fs, n, seed=self._rng)
        else:
            bn = np.zeros(n)

        return bc + wn + pn + bn


class IMUNoise:
    """
    Provides an interface for generating random IMU sensor measurement noise with
    the following contributions for each sensor axis (x, y, z):

    - **N**: White noise (noise density).
    - **B**: Flicker noise (sometimes referred to as 'pink noise' or 'bias instability').
    - **K**: Drift / Brownian noise (optional).
    - **bc**: Constant bias (optional).

    A white sequence, ``WN[k]``, with spectral density ``N**2`` is generated by drawing samples
    from a Normal distribution with standard deviation ``N * sqrt(fs)``.

    A flicker noise (or pink noise) sequence, ``PN[k]``, is simulated using a first-order
    Gauss-Markov (GM) process with long-term standard deviation ``B`` and correlation
    time ``tau_cb``.

    A Brownian noise (or drift) sequence, ``BN[k]``, is simulated using one of the
    following processes, depending on whether the correlation time, ``tau_ck``,
    is provided or not:

    - Random walk (RW) process (if no correlation time ``tau_ck`` is provided).
    - First-order Gauss-Markov (GM) process, with a long-term  standard deviation
      ``K * sqrt(tau_ck / 2)`` and correlation time ``tau_ck``.

    The total noise is computed as::

        err[k] = bc + WN[k] + PN[k] + BN[k]

    where ``WN[k]``, ``PN[k]``, and ``BN[k]`` represent the white, flicker, and Brownian
    noise contributions, respectively.

    All noise parameters can be given either as a scalar value (same noise
    characteristics for all axes) or as an array-like of size 3 (per-axis values
    for x, y, z). The default values correspond to the SMS Motion 2 noise level.

    Parameters
    ----------
    acc_noise_density : float or array-like of size 3, optional
        Accelerometer noise density (velocity random walk), **N**, in (m/s^2)/√Hz.
        Defaults to 0.0007 (m/s^2)/√Hz (SMS Motion 2 noise level).
    acc_bias_stability : float or array-like of size 3, optional
        Accelerometer bias stability (flicker noise), **B**, in m/s^2. Defaults to
        0.0005 m/s^2 (SMS Motion 2 noise level).
    acc_bias_corr_time : float or array-like of size 3, optional
        Accelerometer bias correlation time, **tau_cb**, in seconds. Defaults to 50.0 s.
    acc_drift_rate : float or array-like of size 3, optional
        Accelerometer drift rate (Brownian noise), **K**, in (m/s^2)*√Hz. Defaults
        to ``None`` (no drift).
    acc_drift_corr_time : float or array-like of size 3, optional
        Accelerometer drift correlation time, **tau_ck**, in seconds. If ``None``
        (default), the drift is modeled as a random walk (RW) process. Otherwise,
        it is modeled as a first-order Gauss-Markov (GM) process.
    acc_constant_bias : float or array-like of size 3, optional
        Accelerometer constant bias, **bc**, in m/s^2. Defaults to 0.0 m/s^2.
    gyro_noise_density : float or array-like of size 3, optional
        Gyroscope noise density (angular random walk), **N**, in (rad/s)/√Hz.
        Defaults to 0.00005 (rad/s)/√Hz (SMS Motion 2 noise level).
    gyro_bias_stability : float or array-like of size 3, optional
        Gyroscope bias stability (flicker noise), **B**, in rad/s. Defaults to
        0.00005 rad/s (SMS Motion 2 noise level).
    gyro_bias_corr_time : float or array-like of size 3, optional
        Gyroscope bias correlation time, **tau_cb**, in seconds. Defaults to 50.0 s.
    gyro_drift_rate : float or array-like of size 3, optional
        Gyroscope drift rate (Brownian noise), **K**, in (rad/s)*√Hz. Defaults
        to ``None`` (no drift).
    gyro_drift_corr_time : float or array-like of size 3, optional
        Gyroscope drift correlation time, **tau_ck**, in seconds. If ``None``
        (default), the drift is modeled as a random walk (RW) process. Otherwise,
        it is modeled as a first-order Gauss-Markov (GM) process.
    gyro_constant_bias : float or array-like of size 3, optional
        Gyroscope constant bias, **bc**, in rad/s. Defaults to 0.0 rad/s.
    seed : int, optional
        A seed used to initialize a random number generator.

    Examples
    --------

    Default noise parameters (SMS Motion 2 noise level) for all axes:

    .. code-block:: python

        imu_noise = IMUNoise()

    Different noise characteristics for each axis:

    .. code-block:: python

        imu_noise = IMUNoise(
            acc_noise_density=(7.0e-4, 7.0e-4, 8.0e-4),  # (m/s^2)/sqrt(Hz)
            acc_bias_stability=(5.0e-4, 5.0e-4, 6.0e-4),  # m/s^2
            acc_bias_corr_time=50.0,  # s
            acc_drift_rate=1.0e-7,  # (m/s^2)*sqrt(Hz)
            acc_drift_corr_time=3_600.0,  # s
            acc_constant_bias=(0.1, 0.2, 0.3),  # m/s^2
            gyro_noise_density=(5.0e-5, 5.0e-5, 6.0e-5),  # (rad/s)/sqrt(Hz)
            gyro_bias_stability=(3.0e-5, 3.0e-5, 4.0e-5),  # rad/s
            gyro_bias_corr_time=50.0,  # s
            gyro_drift_rate=(4.0e-7, 4.0e-7, 5.0e-7),  # (rad/s)*sqrt(Hz)
            gyro_drift_corr_time=3_600.0,  # s
            gyro_constant_bias=(0.04, 0.05, 0.06),  # rad/s
        )

    See Also
    --------
    smsfusion.NoiseModel : Generates the specific noise for one single sensor axis.

    """

    def __init__(
        self,
        *,
        acc_noise_density: ArrayLike = ACC_NOISE_DENSITY,
        acc_bias_stability: ArrayLike = ACC_BIAS_STABILITY,
        acc_bias_corr_time: ArrayLike = ACC_BIAS_CORR_TIME,
        acc_drift_rate: ArrayLike | None = None,
        acc_drift_corr_time: ArrayLike | None = None,
        acc_constant_bias: ArrayLike = 0.0,
        gyro_noise_density: ArrayLike = GYRO_NOISE_DENSITY,
        gyro_bias_stability: ArrayLike = GYRO_BIAS_STABILITY,
        gyro_bias_corr_time: ArrayLike = GYRO_BIAS_CORR_TIME,
        gyro_drift_rate: ArrayLike | None = None,
        gyro_drift_corr_time: ArrayLike | None = None,
        gyro_constant_bias: ArrayLike = 0.0,
        seed: int | None = None,
    ) -> None:
        self._seed = seed

        # Per-axis noise parameters (keys correspond to NoiseModel arguments)
        self._err_acc = {
            "N": self._full(acc_noise_density),
            "B": self._full(acc_bias_stability),
            "tau_cb": self._full(acc_bias_corr_time),
            "K": self._full(acc_drift_rate),
            "tau_ck": self._full(acc_drift_corr_time),
            "bc": self._full(acc_constant_bias),
        }
        self._err_gyro = {
            "N": self._full(gyro_noise_density),
            "B": self._full(gyro_bias_stability),
            "tau_cb": self._full(gyro_bias_corr_time),
            "K": self._full(gyro_drift_rate),
            "tau_ck": self._full(gyro_drift_corr_time),
            "bc": self._full(gyro_constant_bias),
        }

        self._err_list = self._to_list(self._err_acc) + self._to_list(self._err_gyro)

    @staticmethod
    def _full(value: ArrayLike | None) -> list[float | None]:
        """Broadcast a scalar or per-axis parameter value to a list of size 3."""
        if value is None:
            return [None, None, None]
        value = np.asarray_chkfinite(value, dtype=np.float64)
        if value.size == 1:
            return [value.item()] * 3
        elif value.size == 3:
            return value.flatten().tolist()
        else:
            raise ValueError(
                "Parameter values must be a scalar or an array-like of size 3."
            )

    @staticmethod
    def _to_list(
        dict_of_lists: dict[str, list[float | None]],
    ) -> list[dict[str, Any]]:
        """Convert dict of lists to list of dicts."""
        return [
            dict(zip(dict_of_lists.keys(), values_j))
            for values_j in zip(*dict_of_lists.values())
        ]

    def __call__(self, fs: float, n: int) -> NDArray[np.float64]:
        """
        Generates discrete-time random IMU measurement noise.

        Parameters
        ----------
        fs : float
            Sampling frequency in Hz.
        n : int
            Number of samples to generate.

        Returns
        -------
        numpy.ndarray, shape (n, 6)
            Noise sequences for the IMU sensor signals: Ax, Ay, Az, Gx, Gy, Gz
            (in that order).

        Notes
        -----
        The generated noise will have units corresponding to the noise
        parameters given during initialization.
        """
        # Generate seeds for each noise component based on class seed
        seeds = np.random.SeedSequence(self._seed).generate_state(6, "uint64")
        x = np.column_stack(
            [NoiseModel(**self._err_list[i], seed=seeds[i])(fs, n) for i in range(6)]
        )
        return x
